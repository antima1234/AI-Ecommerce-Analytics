-- Q37. [STORED PROCEDURE] Reusable lookup: full order history for one customer.
--      Usage:  CALL sp_customer_order_history('CUST00001');
DELIMITER $$

CREATE PROCEDURE sp_customer_order_history(IN p_customer_id VARCHAR(10))
BEGIN
    SELECT
        o.Order_ID,
        o.Order_Date,
        o.Order_Status,
        oi.Product_ID,
        oi.Category,
        oi.Quantity,
        oi.Sales,
        oi.Profit
    FROM orders o
    JOIN order_items oi ON o.Order_ID = oi.Order_ID
    WHERE o.Customer_ID = p_customer_id
    ORDER BY o.Order_Date DESC;
END$$

DELIMITER ;

