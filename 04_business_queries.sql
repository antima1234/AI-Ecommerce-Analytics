-- Q40. [KPI] Company-wide headline metrics (for the Executive Dashboard).
SELECT
    ROUND(SUM(Sales), 2)                                    AS Total_Revenue,
    ROUND(SUM(Profit), 2)                                   AS Total_Profit,
    ROUND(SUM(Profit) / SUM(Sales) * 100, 1)                AS Profit_Margin_Pct,
    (SELECT COUNT(DISTINCT Order_ID) FROM order_items)      AS Total_Orders,
    (SELECT COUNT(*) FROM customers)                        AS Total_Customers,
    ROUND(SUM(Sales) / (SELECT COUNT(DISTINCT Order_ID) FROM order_items), 2) AS Avg_Order_Value
FROM order_items;

-- Q41. [KPI] Return rate by category (product quality / fit signal).
SELECT
    Category,
    COUNT(*)                                                            AS Total_Items,
    SUM(CASE WHEN Return_Flag = 'Yes' THEN 1 ELSE 0 END)               AS Returned_Items,
    ROUND(SUM(CASE WHEN Return_Flag = 'Yes' THEN 1 ELSE 0 END) * 100.0
          / COUNT(*), 1)                                                AS Return_Rate_Pct
FROM order_items
GROUP BY Category
ORDER BY Return_Rate_Pct DESC;

-- Q42. [KPI] Churn rate by customer segment (retention health check).
SELECT
    Customer_Segment,
    COUNT(*)                                          AS Total_Customers,
    SUM(Churned)                                       AS Churned_Customers,
    ROUND(SUM(Churned) * 100.0 / COUNT(*), 1)          AS Churn_Rate_Pct
FROM customers
GROUP BY Customer_Segment
ORDER BY Churn_Rate_Pct DESC;
